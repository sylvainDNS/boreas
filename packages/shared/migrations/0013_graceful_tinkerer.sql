-- Rang fractionnaire des Feeds (#110, ADR 0020) — fondation de l'ordre manuel.
--
-- Expand-only (ADR 0011) : on AJOUTE une colonne `rank` (TEXT NOT NULL), jamais de
-- renommage destructif. SQLite exige un DEFAULT constant pour un ADD COLUMN NOT NULL
-- (comme `folders.rank` en 0012) ; `'a0'` est une clé fractional-indexing valide qui
-- ne sert qu'à satisfaire la contrainte le temps du backfill — tout INSERT applicatif
-- (POST /api/feeds, déplacement, import OPML) fournit ensuite un rang explicite.
ALTER TABLE `feeds` ADD `rank` text NOT NULL DEFAULT 'a0';--> statement-breakpoint

-- Backfill **scopé par conteneur** (ADR 0020) : le rang d'un Feed est ordonné au sein
