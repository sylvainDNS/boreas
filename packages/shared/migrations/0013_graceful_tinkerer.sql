-- — et non globalement. On partitionne donc par `folder_id` ; `ROW_NUMBER()` repart à 1
-- dans chaque conteneur, et l'ordre initial est `title ASC, url ASC, id ASC` (départage
-- stable). Les clés ci-dessous sont des clés `fractional-indexing` VALIDES pré-générées
-- (generateNKeysBetween(null, null, 256), identiques à 0012) : deux clés backfillées
-- adjacentes d'un même conteneur restent toujours intercalables par `rankBetween` (régression
